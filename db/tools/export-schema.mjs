#!/usr/bin/env node
/**
 * Exports database objects from a live database into version-controlled files:
 *
 *   db/functions/<schema>.<name>.sql     CREATE OR REPLACE FUNCTION ...
 *   db/procedures/<schema>.<name>.sql    CREATE OR REPLACE PROCEDURE ...
 *   db/views/<schema>.<name>.sql         CREATE OR REPLACE VIEW ...
 *   db/triggers/<schema>.<table>.<trigger>.sql
 *   db/schema.dbml                        dbdiagram.io diagram (tables, enums, refs, groups)
 *
 * Usage:
 *   node db/tools/export-schema.mjs                 # DATABASE_URL from .env.local
 *   node db/tools/export-schema.mjs --env .env      # another env file
 *
 * Read-only: only catalog queries run (inside a READ ONLY transaction).
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(path.join(root, "package.json"));
const dotenv = require("dotenv");
const { Client } = require("pg");

const args = process.argv.slice(2);
const envFile = args.includes("--env") ? args[args.indexOf("--env") + 1] : ".env.local";
dotenv.config({ path: path.join(root, envFile), quiet: true });

const SCHEMAS = ["public", "identity", "profile", "catalog", "course", "learning", "challenge", "roadmap", "community", "commerce", "storage"];
const DB_DIR = path.join(root, "db");
const OUT = {
    functions: path.join(DB_DIR, "functions"),
    procedures: path.join(DB_DIR, "procedures"),
    views: path.join(DB_DIR, "views"),
    triggers: path.join(DB_DIR, "triggers"),
};

const HEADER = (what) => `-- ${what}\n-- Generated by db/tools/export-schema.mjs from the live database. Do not edit by hand:\n-- change the database through a migration in db/migrations, then re-run the exporter.\n\n`;

function resetDir(dir) {
    fs.mkdirSync(dir, { recursive: true });
    for (const f of fs.readdirSync(dir)) {
        if (f.endsWith(".sql")) fs.unlinkSync(path.join(dir, f));
    }
}

const client = new Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 15000 });
await client.connect();
await client.query("BEGIN READ ONLY");
const q = async (text, params = []) => (await client.query(text, params)).rows;

try {
    // ------------------------------------------------------------- routines
    const routines = await q(`
        SELECT n.nspname AS schema, p.proname AS name, p.prokind AS kind,
               pg_get_function_identity_arguments(p.oid) AS args,
               pg_get_functiondef(p.oid) AS def,
               obj_description(p.oid, 'pg_proc') AS comment
        FROM pg_proc p
        JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = ANY($1)
          AND p.prokind IN ('f', 'p')
          AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
        ORDER BY 1, 2`, [SCHEMAS]);

    resetDir(OUT.functions);
    resetDir(OUT.procedures);
    const seen = new Map();
    for (const r of routines) {
        const base = `${r.schema}.${r.name}`;
        const count = (seen.get(base) || 0) + 1;
        seen.set(base, count);
        const file = `${base}${count > 1 ? `_${count}` : ""}.sql`;
        const kind = r.kind === "p" ? "procedure" : "function";
        let body = HEADER(`${kind} ${base}(${r.args})`) + r.def.trim() + ";\n";
        if (r.comment) body += `\nCOMMENT ON ${kind.toUpperCase()} ${base}(${r.args}) IS ${quote(r.comment)};\n`;
        fs.writeFileSync(path.join(r.kind === "p" ? OUT.procedures : OUT.functions, file), body);
    }

    // ------------------------------------------------------------- views
    const views = await q(`
        SELECT schemaname AS schema, viewname AS name, pg_get_viewdef(format('%I.%I', schemaname, viewname)::regclass, true) AS def
        FROM pg_views WHERE schemaname = ANY($1) ORDER BY 1, 2`, [SCHEMAS]);
    resetDir(OUT.views);
    for (const v of views) {
        fs.writeFileSync(
            path.join(OUT.views, `${v.schema}.${v.name}.sql`),
            HEADER(`view ${v.schema}.${v.name}`) + `CREATE OR REPLACE VIEW ${v.schema}.${v.name} AS\n${v.def.trim().replace(/;$/, "")};\n`
        );
    }

    // ------------------------------------------------------------- triggers
    const triggers = await q(`
        SELECT n.nspname AS schema, c.relname AS tbl, t.tgname AS name, pg_get_triggerdef(t.oid, true) AS def
        FROM pg_trigger t
        JOIN pg_class c ON c.oid = t.tgrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE NOT t.tgisinternal AND n.nspname = ANY($1)
        ORDER BY 1, 2, 3`, [SCHEMAS]);
    resetDir(OUT.triggers);
    for (const t of triggers) {
        fs.writeFileSync(
            path.join(OUT.triggers, `${t.schema}.${t.tbl}.${t.name}.sql`),
            HEADER(`trigger ${t.name} on ${t.schema}.${t.tbl}`) +
            `DROP TRIGGER IF EXISTS ${t.name} ON ${t.schema}.${t.tbl};\n${t.def};\n`
        );
    }

    // ------------------------------------------------------------- dbml
    const dbml = await buildDbml();
    fs.writeFileSync(path.join(DB_DIR, "schema.dbml"), dbml);

    console.log(`functions: ${routines.filter((r) => r.kind === "f").length}, procedures: ${routines.filter((r) => r.kind === "p").length}, views: ${views.length}, triggers: ${triggers.length}`);
    console.log("written: db/functions, db/procedures, db/views, db/triggers, db/schema.dbml");
} finally {
    await client.query("ROLLBACK");
    await client.end();
}

// =============================================================================
function quote(s) {
    return `'${String(s).replace(/'/g, "''")}'`;
}

function dbmlName(s) {
    return /^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s.replace(/"/g, '\\"')}"`;
}

function shortType(t) {
    return t
        .replace(/^timestamp\(\d\) without time zone$|^timestamp without time zone$/, "timestamp")
        .replace(/^timestamp\(\d\) with time zone$|^timestamp with time zone$/, "timestamptz")
        .replace(/^character varying/, "varchar")
        .replace(/^character\b/, "char")
        .replace(/^integer$/, "int")
        .replace(/^double precision$/, "float8");
}

function dbmlType(t) {
    const s = shortType(t);
    return /^[\w.]+(\(\d+(,\s?\d+)?\))?(\[\])?$/.test(s) ? s.replace(/\s/g, "") : `"${s}"`;
}

function dbmlDefault(def) {
    if (def == null) return null;
    if (/^nextval\(/.test(def)) return null; // serial -> shown as increment
    const literal = def.match(/^'((?:[^']|'')*)'(::[\w ."]+)*$/);
    if (literal) return `'${literal[1].replace(/''/g, "\\'")}'`;
    if (/^-?\d+(\.\d+)?$/.test(def)) return def;
    if (def === "true" || def === "false") return def;
    const numCast = def.match(/^\(?(-?\d+(\.\d+)?)\)?::[\w ]+$/);
    if (numCast) return numCast[1];
    return `\`${def}\``;
}

async function buildDbml() {
    const schemaComments = await q(`SELECT nspname AS schema, obj_description(oid, 'pg_namespace') AS comment FROM pg_namespace WHERE nspname = ANY($1)`, [SCHEMAS]);
    const enums = await q(`
        SELECT n.nspname AS schema, t.typname AS name, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) AS labels
        FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE n.nspname = ANY($1) GROUP BY 1, 2 ORDER BY 1, 2`, [SCHEMAS]);
    const tables = await q(`
        SELECT c.oid, n.nspname AS schema, c.relname AS name, obj_description(c.oid, 'pg_class') AS comment
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind IN ('r', 'p') AND n.nspname = ANY($1) ORDER BY 2, 3`, [SCHEMAS]);
    const columns = await q(`
        SELECT a.attrelid AS oid, a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type,
               a.attnotnull AS not_null, a.attidentity AS identity, pg_get_expr(d.adbin, d.adrelid) AS def,
               col_description(a.attrelid, a.attnum) AS comment, tn.nspname AS type_schema, ty.typtype
        FROM pg_attribute a
        JOIN pg_type ty ON ty.oid = a.atttypid
        JOIN pg_namespace tn ON tn.oid = ty.typnamespace
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = ANY($1) AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attrelid, a.attnum`, [tables.map((t) => t.oid)]);
    const constraints = await q(`
        SELECT con.conrelid AS oid, con.conname AS name, con.contype AS type,
               (SELECT array_agg(a.attname::text ORDER BY k.ord) FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum) AS cols,
               fn.nspname AS ref_schema, fc.relname AS ref_table,
               (SELECT array_agg(a.attname::text ORDER BY k.ord) FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord)
                  JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum) AS ref_cols,
               con.confdeltype AS on_delete, con.confupdtype AS on_update,
               pg_get_constraintdef(con.oid) AS def
        FROM pg_constraint con
        LEFT JOIN pg_class fc ON fc.oid = con.confrelid
        LEFT JOIN pg_namespace fn ON fn.oid = fc.relnamespace
        WHERE con.conrelid = ANY($1) AND con.contype IN ('p', 'u', 'f', 'c')
        ORDER BY con.conrelid, con.conname`, [tables.map((t) => t.oid)]);
    const indexes = await q(`
        SELECT i.indrelid AS oid, ic.relname AS name, i.indisunique AS is_unique,
               pg_get_expr(i.indpred, i.indrelid) AS predicate,
               (SELECT array_agg(pg_get_indexdef(i.indexrelid, k, true) ORDER BY k) FROM generate_series(1, i.indnkeyatts) k) AS parts,
               am.amname AS method
        FROM pg_index i
        JOIN pg_class ic ON ic.oid = i.indexrelid
        JOIN pg_am am ON am.oid = ic.relam
        WHERE i.indrelid = ANY($1)
          AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)
        ORDER BY i.indrelid, ic.relname`, [tables.map((t) => t.oid)]);
    const views = await q(`SELECT schemaname AS schema, viewname AS name FROM pg_views WHERE schemaname = ANY($1) ORDER BY 1, 2`, [SCHEMAS]);

    const byOid = (rows) => rows.reduce((m, r) => m.set(String(r.oid), [...(m.get(String(r.oid)) || []), r]), new Map());
    const colsBy = byOid(columns);
    const consBy = byOid(constraints);
    const idxBy = byOid(indexes);
    const action = { a: null, r: "restrict", c: "cascade", n: "set null", d: "set default" };

    const out = [];
    out.push(`// CodeDev database diagram - paste into https://dbdiagram.io`);
    out.push(`// Generated by db/tools/export-schema.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`);
    out.push("");
    out.push(`Project codedev {\n  database_type: 'PostgreSQL'\n  Note: '''\n${schemaComments.filter((s) => s.comment).map((s) => `  - **${s.schema}**: ${s.comment}`).join("\n")}\n  - Views: ${views.map((v) => `${v.schema}.${v.name}`).join(", ") || "none"}\n  '''\n}`);
    out.push("");

    for (const e of enums) {
        out.push(`Enum ${e.schema}.${dbmlName(e.name)} {`);
        for (const label of e.labels) out.push(`  "${label}"`);
        out.push("}");
        out.push("");
    }

    const refs = [];
    for (const t of tables) {
        const cols = colsBy.get(String(t.oid)) || [];
        const cons = consBy.get(String(t.oid)) || [];
        const pk = cons.find((c) => c.type === "p");
        const singleUnique = new Set(cons.filter((c) => c.type === "u" && c.cols.length === 1).map((c) => c.cols[0]));
        const checks = cons.filter((c) => c.type === "c");

        out.push(`Table ${t.schema}.${dbmlName(t.name)} {`);
        for (const col of cols) {
            const settings = [];
            if (pk && pk.cols.length === 1 && pk.cols[0] === col.name) settings.push("pk");
            if (col.identity || /^nextval\(/.test(col.def || "")) settings.push("increment");
            if (col.not_null && !(pk && pk.cols.includes(col.name))) settings.push("not null");
            if (singleUnique.has(col.name)) settings.push("unique");
            const def = dbmlDefault(col.def);
            if (def !== null) settings.push(`default: ${def}`);
            if (col.comment) settings.push(`note: ${quote(col.comment)}`);
            const type = col.typtype === "e" ? `${col.type_schema}.${col.type.replace(/^.*\./, "")}` : dbmlType(col.type);
            out.push(`  ${dbmlName(col.name)} ${type}${settings.length ? ` [${settings.join(", ")}]` : ""}`);
        }

        const idxLines = [];
        if (pk && pk.cols.length > 1) idxLines.push(`    (${pk.cols.join(", ")}) [pk]`);
        for (const u of cons.filter((c) => c.type === "u" && c.cols.length > 1)) {
            idxLines.push(`    (${u.cols.join(", ")}) [unique, name: '${u.name}']`);
        }
        for (const ix of idxBy.get(String(t.oid)) || []) {
            const parts = ix.parts.map((p) => (/^[a-z_][a-z0-9_]*$/.test(p) ? p : `\`${p}\``));
            const opts = [`name: '${ix.name}'`];
            if (ix.is_unique) opts.unshift("unique");
            if (ix.method !== "btree") opts.push(`type: ${ix.method}`);
            if (ix.predicate) opts.push(`note: 'WHERE ${ix.predicate.replace(/'/g, "\\'")}'`);
            idxLines.push(`    ${parts.length === 1 ? parts[0] : `(${parts.join(", ")})`} [${opts.join(", ")}]`);
        }
        if (idxLines.length) {
            out.push("");
            out.push("  indexes {");
            out.push(...idxLines);
            out.push("  }");
        }

        const notes = [];
        if (t.comment) notes.push(t.comment);
        for (const c of checks) notes.push(`${c.name}: ${c.def}`);
        if (notes.length) {
            out.push("");
            out.push(`  Note: '''\n  ${notes.join("\n  ").replace(/'''/g, "")}\n  '''`);
        }
        out.push("}");
        out.push("");

        for (const fk of cons.filter((c) => c.type === "f")) {
            const src = `${t.schema}.${dbmlName(t.name)}.${fk.cols.length === 1 ? fk.cols[0] : `(${fk.cols.join(", ")})`}`;
            const dst = `${fk.ref_schema}.${dbmlName(fk.ref_table)}.${fk.ref_cols.length === 1 ? fk.ref_cols[0] : `(${fk.ref_cols.join(", ")})`}`;
            const opts = [];
            if (action[fk.on_delete]) opts.push(`delete: ${action[fk.on_delete]}`);
            if (action[fk.on_update]) opts.push(`update: ${action[fk.on_update]}`);
            refs.push(`Ref ${fk.name}: ${src} > ${dst}${opts.length ? ` [${opts.join(", ")}]` : ""}`);
        }
    }

    out.push("// ---------------------------------------------------------------- relationships");
    out.push(...refs);
    out.push("");

    out.push("// ---------------------------------------------------------------- schema groups");
    for (const schema of SCHEMAS) {
        const members = tables.filter((t) => t.schema === schema);
        if (!members.length) continue;
        out.push(`TableGroup ${schema} {`);
        for (const m of members) out.push(`  ${schema}.${dbmlName(m.name)}`);
        out.push("}");
        out.push("");
    }

    return out.join("\n");
}
