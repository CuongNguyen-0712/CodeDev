#!/usr/bin/env node
/**
 * Builds an idempotent SQL seed for one course from content/courses/<course>/:
 *   course.json                         course, modules, lessons (lesson.content_source = Sanity _id)
 *   <lesson>/challenges.json            challenges, quiz questions/options, coding configs, test cases
 *   <lesson>/storage-manifest.json      storage.assets + challenge.coding_files (from upload-storage.mjs)
 *
 * Re-running is safe: rows are matched by public ids / natural keys and updated in place.
 * Quiz questions are only inserted the first time (learners' answers reference them);
 * test cases are replaced on every run.
 *
 * Usage: node content/tools/build-seed.mjs content/courses/<course>   -> db/seeds/<course>.sql
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const courseDir = path.resolve(process.argv[2]);
const course = JSON.parse(fs.readFileSync(path.join(courseDir, "course.json"), "utf8"));

const lit = (value) => {
    if (value === null || value === undefined) return "NULL";
    if (typeof value === "number") return String(value);
    if (typeof value === "boolean") return value ? "true" : "false";
    return `'${String(value).replace(/'/g, "''")}'`;
};
const json = (value) => lit(JSON.stringify(value));
const courseId = `(SELECT id FROM catalog.course WHERE public_id = ${lit(course.publicId)})`;

const out = [];
out.push(`-- Seed: course ${course.publicId}`);
out.push(`-- Generated by content/tools/build-seed.mjs from content/courses/${course.publicId}. Do not edit by hand.`);
out.push(`-- Idempotent: safe to run again after editing the content files.`);
out.push("");
out.push("BEGIN;");
out.push("");
// Older rows were inserted with explicit ids, which leaves sequences behind the data.
// Move each sequence forward to max(id) (never backwards) before inserting.
out.push(`DO $$
DECLARE
    t text;
    seq text;
BEGIN
    FOREACH t IN ARRAY ARRAY['catalog.course', 'course.module', 'course.lesson', 'challenge.challenges', 'challenge.questions',
                             'challenge.question_options', 'challenge.challenge_test_cases', 'challenge.coding_files', 'storage.assets'] LOOP
        seq := pg_get_serial_sequence(t, 'id');
        IF seq IS NOT NULL THEN
            EXECUTE format('SELECT setval(%L, GREATEST((SELECT COALESCE(max(id), 0) FROM %s), (SELECT last_value FROM %s)))', seq, t, seq);
        END IF;
    END LOOP;
END $$;`);
out.push("");
if (course.existing) {
    // Course authored before this pipeline: keep its catalog row, only apply `update`.
    const columns = { durationMinutes: "duration", reward: "reward", description: "description", concept: "concept" };
    const sets = Object.entries(course.update || {}).filter(([k]) => columns[k]).map(([k, v]) => `${columns[k]} = ${lit(v)}`);
    out.push(`DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM catalog.course WHERE public_id = ${lit(course.publicId)} AND is_deleted = false) THEN
        RAISE EXCEPTION 'course ${course.publicId} does not exist';
    END IF;
END $$;`);
    if (sets.length) out.push(`UPDATE catalog.course SET ${sets.join(", ")}, updated_at = now() WHERE public_id = ${lit(course.publicId)};`);
} else out.push(`INSERT INTO catalog.course (public_id, title, concept, description, image, level, duration, instructor, cost, point_price, reward, language_id, category_id, is_hidden, is_deleted)
VALUES (${lit(course.publicId)}, ${lit(course.title)}, ${lit(course.concept)}, ${lit(course.description)}, ${lit(course.image)}, ${lit(course.level)}::level_enum, ${lit(course.durationMinutes)}, ${lit(course.instructor)}, ${lit(course.cost)}, ${lit(course.pointPrice)}, ${lit(course.reward)},
        (SELECT id FROM catalog.language WHERE name = ${lit(course.language)}),
        (SELECT id FROM catalog.category WHERE name = ${lit(course.category)}),
        false, false)
ON CONFLICT (public_id) DO UPDATE SET
    title = EXCLUDED.title, concept = EXCLUDED.concept, description = EXCLUDED.description, image = EXCLUDED.image,
    level = EXCLUDED.level, duration = EXCLUDED.duration, instructor = EXCLUDED.instructor, cost = EXCLUDED.cost,
    point_price = EXCLUDED.point_price, reward = EXCLUDED.reward, language_id = EXCLUDED.language_id,
    category_id = EXCLUDED.category_id, updated_at = now();`);
out.push("");

for (const module of course.modules) {
    const moduleId = `(SELECT id FROM course.module WHERE course_id = ${courseId} AND order_index = ${module.orderIndex} AND is_deleted = false LIMIT 1)`;
    out.push(`-- module ${module.orderIndex}: ${module.title}`);
    out.push(`UPDATE course.module SET title = ${lit(module.title)}, updated_at = now() WHERE id = ${moduleId};`);
    out.push(`INSERT INTO course.module (course_id, title, order_index)
SELECT ${courseId}, ${lit(module.title)}, ${module.orderIndex}
WHERE NOT EXISTS (SELECT 1 FROM course.module WHERE course_id = ${courseId} AND order_index = ${module.orderIndex} AND is_deleted = false);`);
    out.push("");

    for (const lesson of module.lessons) {
        const lessonId = `(SELECT id FROM course.lesson WHERE content_source = ${lit(lesson.sanityId)} AND is_deleted = false LIMIT 1)`;
        if (lesson.existing) {
            // Authored before this pipeline (challenges live only in the DB): leave it untouched.
            out.push(`-- lesson ${module.orderIndex}.${lesson.orderIndex}: ${lesson.title} (existing, Sanity ${lesson.sanityId})`);
            out.push("");
            continue;
        }
        out.push(`-- lesson ${module.orderIndex}.${lesson.orderIndex}: ${lesson.title} (Sanity ${lesson.sanityId})`);
        out.push(`UPDATE course.lesson SET title = ${lit(lesson.title)}, order_index = ${lesson.orderIndex}, module_id = ${moduleId}, updated_at = now() WHERE id = ${lessonId};`);
        out.push(`INSERT INTO course.lesson (module_id, title, content_type, content_source, order_index)
SELECT ${moduleId}, ${lit(lesson.title)}, 'sanity', ${lit(lesson.sanityId)}, ${lesson.orderIndex}
WHERE NOT EXISTS (SELECT 1 FROM course.lesson WHERE content_source = ${lit(lesson.sanityId)} AND is_deleted = false);`);
        out.push("");

        const lessonDir = path.join(courseDir, lesson.folder);
        const { challenges } = JSON.parse(fs.readFileSync(path.join(lessonDir, "challenges.json"), "utf8"));
        const manifestPath = path.join(lessonDir, "storage-manifest.json");
        const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : { files: [] };

        for (const ch of challenges) {
            const challengeId = `(SELECT id FROM challenge.challenges WHERE public_id = ${lit(ch.publicId)})`;
            out.push(`-- challenge ${ch.publicId} (${ch.type})`);
            out.push(`INSERT INTO challenge.challenges (public_id, course_id, module_id, lesson_id, name, title, description, status, difficulty, type, points, is_published, is_deleted)
VALUES (${lit(ch.publicId)}, ${courseId}, ${moduleId}, ${lessonId}, ${lit(ch.name)}, ${lit(ch.title)}, ${lit(ch.description)}, 'open', ${lit(ch.difficulty)}::difficulty_question, ${lit(ch.type)}, ${lit(ch.points)}, true, false)
ON CONFLICT (public_id) DO UPDATE SET
    course_id = EXCLUDED.course_id, module_id = EXCLUDED.module_id, lesson_id = EXCLUDED.lesson_id, name = EXCLUDED.name,
    title = EXCLUDED.title, description = EXCLUDED.description, difficulty = EXCLUDED.difficulty, type = EXCLUDED.type,
    points = EXCLUDED.points, is_published = true, is_deleted = false, updated_at = now();`);

            if (ch.type === "quiz") {
                ch.questions.forEach((q, index) => {
                    const options = q.options.map((o) => `(${lit(o.text)}, ${lit(Boolean(o.correct))})`).join(",\n        ");
                    out.push(`WITH q AS (
    INSERT INTO challenge.questions (challenge_id, question, type, explanation, order_index, points)
    SELECT ${challengeId}, ${lit(q.question)}, ${lit(q.type)}::question_type, ${lit(q.explanation)}, ${index + 1}, ${lit(q.points)}
    WHERE NOT EXISTS (SELECT 1 FROM challenge.questions WHERE challenge_id = ${challengeId} AND order_index = ${index + 1})
    RETURNING id
)
INSERT INTO challenge.question_options (question_id, option_text, is_correct)
SELECT q.id, o.option_text, o.is_correct
FROM q, (VALUES
        ${options}
    ) AS o(option_text, is_correct);`);
                });
            } else {
                const cfg = ch.coding;
                out.push(`INSERT INTO challenge.coding_configs (challenge_id, execution_mode, time_limit_ms, memory_limit_mb, max_attempts, scoring_mode)
VALUES (${challengeId}, ${lit(cfg.executionMode)}, ${cfg.timeLimitMs}, ${cfg.memoryLimitMb}, ${lit(cfg.maxAttempts)}, ${lit(cfg.scoringMode)})
ON CONFLICT (challenge_id) DO UPDATE SET
    execution_mode = EXCLUDED.execution_mode, time_limit_ms = EXCLUDED.time_limit_ms, memory_limit_mb = EXCLUDED.memory_limit_mb,
    max_attempts = EXCLUDED.max_attempts, scoring_mode = EXCLUDED.scoring_mode, updated_at = now();`);
                out.push(`DELETE FROM challenge.challenge_test_cases WHERE challenge_id = ${challengeId};`);
                const rows = ch.tests.map((t, i) =>
                    `(${challengeId}, ${lit(t.name)}, ${json(t.input)}, ${json(t.expected)}, ${t.score ?? 1}, ${lit(!t.hidden)}, ${lit(Boolean(t.hidden))}, ${i + 1})`
                ).join(",\n       ");
                out.push(`INSERT INTO challenge.challenge_test_cases (challenge_id, name, input_data, expected_output, score, is_sample, is_hidden, sort_order)
VALUES ${rows};`);

                for (const file of manifest.files.filter((f) => f.challengePublicId === ch.publicId)) {
                    const assetPublicId = `ast_${ch.publicId}_${file.role}`;
                    out.push(`INSERT INTO storage.assets (public_id, provider, object_key, resource_type, mine_type, file_size, original_name)
VALUES (${lit(assetPublicId)}, 's3', ${lit(file.key)}, 'raw', ${lit(file.contentType.split(";")[0])}, ${file.size}, ${lit(file.originalName)})
ON CONFLICT (public_id) DO UPDATE SET object_key = EXCLUDED.object_key, file_size = EXCLUDED.file_size, mine_type = EXCLUDED.mine_type, original_name = EXCLUDED.original_name, updated_at = now();`);
                    const filePath = file.role === "harness" ? "harness.js" : (ch.coding.filePath || "starter.js");
                    out.push(`INSERT INTO challenge.coding_files (challenge_id, language, file_path, file_role, asset_id)
VALUES (${challengeId}, ${lit(ch.coding.language)}, ${lit(filePath)}, ${lit(file.role)}, (SELECT id FROM storage.assets WHERE public_id = ${lit(assetPublicId)}))
ON CONFLICT ON CONSTRAINT uq_coding_files_path DO UPDATE SET file_role = EXCLUDED.file_role, asset_id = EXCLUDED.asset_id, updated_at = now();`);
                }
            }
            out.push("");
        }

        for (const file of manifest.files.filter((f) => !f.challengePublicId)) {
            out.push(`-- lesson file ${file.key}`);
            out.push(`INSERT INTO storage.assets (public_id, provider, object_key, resource_type, mine_type, file_size, original_name)
VALUES (${lit(`ast_${course.publicId}_${lesson.folder}_${file.role}`.replace(/[^a-zA-Z0-9_]/g, "_"))}, 's3', ${lit(file.key)}, 'raw', ${lit(file.contentType)}, ${file.size}, ${lit(file.originalName)})
ON CONFLICT (public_id) DO UPDATE SET object_key = EXCLUDED.object_key, file_size = EXCLUDED.file_size, updated_at = now();`);
            out.push("");
        }
    }
}

// register_course() only creates history rows for the lessons that exist at enrollment time.
// Learners who enrolled earlier get rows for the new lessons, and the first new lesson is
// unlocked when everything before it is completed (submit_lesson() could not unlock it then).
out.push(`-- learners enrolled before these lessons existed`);
out.push(`INSERT INTO learning.history (user_id, course_id, module_id, lesson_id)
SELECT r.user_id, r.course_id, m.id, l.id
FROM learning.register r
JOIN course.module m ON m.course_id = r.course_id AND m.is_deleted = false
JOIN course.lesson l ON l.module_id = m.id AND l.is_deleted = false
WHERE r.course_id = ${courseId} AND r.is_deleted = false
ON CONFLICT DO NOTHING;`);
out.push(`WITH ordered AS (
    SELECT h.user_id, h.lesson_id, h.status,
           row_number() OVER (PARTITION BY h.user_id ORDER BY m.order_index, l.order_index) AS rn
    FROM learning.history h
    JOIN course.lesson l ON l.id = h.lesson_id AND l.is_deleted = false
    JOIN course.module m ON m.id = l.module_id AND m.is_deleted = false
    WHERE h.course_id = ${courseId}
),
next_lesson AS (
    SELECT DISTINCT ON (o.user_id) o.user_id, o.lesson_id
    FROM ordered o
    WHERE o.status = 'enrolled'
      AND NOT EXISTS (SELECT 1 FROM ordered p WHERE p.user_id = o.user_id AND p.rn < o.rn AND p.status <> 'completed')
    ORDER BY o.user_id, o.rn
)
UPDATE learning.history h
SET status = 'in_progress', updated_at = now()
FROM next_lesson n
JOIN learning.register r ON r.user_id = n.user_id AND r.course_id = ${courseId} AND r.is_deleted = false AND r.status <> 'enrolled'
WHERE h.user_id = n.user_id AND h.course_id = ${courseId} AND h.lesson_id = n.lesson_id;`);
out.push(`UPDATE learning.register r
SET status = 'in_progress'
WHERE r.course_id = ${courseId} AND r.status = 'completed'
  AND EXISTS (SELECT 1 FROM learning.history h WHERE h.user_id = r.user_id AND h.course_id = ${courseId} AND h.status <> 'completed');`);
out.push("");

out.push("COMMIT;");
const target = path.join(root, "db", "seeds", `${course.publicId}.sql`);
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out.join("\n") + "\n");
console.log(`wrote ${path.relative(root, target)}`);
