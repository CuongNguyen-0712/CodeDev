#!/usr/bin/env node
/**
 * Builds an idempotent SQL seed for the career roadmaps from content/roadmaps.json:
 * one roadmap per career role, ordered nodes, and the courses linked to each node (node_course).
 *
 * Roadmap ids are fixed (1..n) and node ids are <roadmap id> * 100 + <position>, so re-running
 * updates rows in place and keeps public ids (URLs) stable. Roadmaps and nodes no longer in the
 * file are removed only while no learner has started them. Courses are linked by public id; a
 * course must exist in content/courses (the seed of that course creates it).
 *
 * Usage: node content/tools/build-roadmaps.mjs   -> db/seeds/roadmaps.sql
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const { roadmaps } = JSON.parse(fs.readFileSync(path.join(root, "content", "roadmaps.json"), "utf8"));

const lit = (value) => {
    if (value === null || value === undefined) return "NULL";
    if (typeof value === "number") return String(value);
    return `'${String(value).replace(/'/g, "''")}'`;
};

const courseIds = new Set(fs.readdirSync(path.join(root, "content", "courses")));
const roadmapRows = [];
const nodeRows = [];
const nodeIds = [];
const linkRows = [];
for (const roadmap of roadmaps) {
    if (roadmap.nodes.length > 99) throw new Error(`${roadmap.title}: at most 99 nodes`);
    roadmapRows.push(`(${roadmap.id}, ${lit(roadmap.title)}, ${lit(roadmap.description)}, ${lit(roadmap.level)}, ${lit(roadmap.role)})`);
    roadmap.nodes.forEach((node, index) => {
        const nodeId = roadmap.id * 100 + index + 1;
        nodeIds.push(nodeId);
        nodeRows.push(`(${nodeId}, ${roadmap.id}, ${lit(node.title)}, ${lit(node.description)}, ${index + 1})`);
        node.courses.forEach((course, priority) => {
            if (!courseIds.has(course)) throw new Error(`${roadmap.title} / ${node.title}: unknown course "${course}"`);
            linkRows.push(`(${nodeId}, ${lit(course)}, ${priority})`);
        });
    });
}
const roadmapIds = roadmaps.map((r) => r.id).join(", ");

const sql = `-- Seed: career roadmaps
-- Generated by content/tools/build-roadmaps.mjs from content/roadmaps.json. Do not edit by hand.
-- Idempotent: safe to run again. Apply after the course seeds (courses are linked by public id).

BEGIN;

DO $$
DECLARE
    v_missing text;
BEGIN
    SELECT string_agg(v.code, ', ') INTO v_missing
    FROM (VALUES ${roadmaps.map((r) => `(${lit(r.role)})`).join(", ")}) v(code)
    WHERE NOT EXISTS (SELECT 1 FROM catalog.career_role cr WHERE cr.code = v.code);
    IF v_missing IS NOT NULL THEN
        RAISE EXCEPTION 'unknown career roles: %', v_missing;
    END IF;
END $$;

INSERT INTO roadmap.roadmaps (id, title, description, level, career_role_id)
SELECT v.id, v.title, v.description, v.level::public.level_enum, cr.id
FROM (VALUES
    ${roadmapRows.join(",\n    ")}
) v(id, title, description, level, role)
JOIN catalog.career_role cr ON cr.code = v.role
ON CONFLICT (id) DO UPDATE SET
    title = EXCLUDED.title, description = EXCLUDED.description, level = EXCLUDED.level,
    career_role_id = EXCLUDED.career_role_id, updated_at = now();

INSERT INTO roadmap.nodes (id, roadmap_id, title, description, order_index)
VALUES
    ${nodeRows.join(",\n    ")}
ON CONFLICT (id) DO UPDATE SET
    roadmap_id = EXCLUDED.roadmap_id, title = EXCLUDED.title, description = EXCLUDED.description,
    order_index = EXCLUDED.order_index, updated_at = now();

-- Links are rebuilt from the file (no learner data hangs off node_course).
DELETE FROM roadmap.node_course nc
USING roadmap.nodes n
WHERE nc.node_id = n.id AND n.roadmap_id IN (${roadmapIds});

INSERT INTO roadmap.node_course (node_id, course_id, priority)
SELECT v.node_id, c.id, v.priority
FROM (VALUES
    ${linkRows.join(",\n    ")}
) v(node_id, course, priority)
JOIN catalog.course c ON c.public_id = v.course;

-- Nodes and roadmaps that left the file go, unless a learner has started them.
DELETE FROM roadmap.nodes n
WHERE n.id NOT IN (${nodeIds.join(", ")})
  AND NOT EXISTS (SELECT 1 FROM roadmap.roadmap_users ru WHERE ru.current_node_id = n.id)
  AND NOT EXISTS (SELECT 1 FROM roadmap.user_progress up WHERE up.node_id = n.id);

DELETE FROM roadmap.roadmaps r
WHERE r.id NOT IN (${roadmapIds})
  AND NOT EXISTS (SELECT 1 FROM roadmap.nodes n WHERE n.roadmap_id = r.id)
  AND NOT EXISTS (SELECT 1 FROM roadmap.roadmap_users ru WHERE ru.roadmap_id = r.id)
  AND NOT EXISTS (SELECT 1 FROM roadmap.user_progress up WHERE up.roadmap_id = r.id);

SELECT setval('roadmap.roadmaps_id_seq', GREATEST((SELECT max(id) FROM roadmap.roadmaps), 1));
SELECT setval('roadmap.roadmap_nodes_id_seq', GREATEST((SELECT max(id) FROM roadmap.nodes), 1));

COMMIT;
`;

const target = path.join(root, "db", "seeds", "roadmaps.sql");
fs.writeFileSync(target, sql);
console.log(`${path.relative(root, target)}: ${roadmaps.length} roadmaps, ${nodeRows.length} nodes, ${linkRows.length} course links`);
